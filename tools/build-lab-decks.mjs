#!/usr/bin/env node
/* Build js/lab-decks.js: the Lesson studio decks SlideForge ships, written into the
 * app itself the way the lessons are (js/lessons-ipdv-week5.js), so every
 * browser's Library has them from the start, under their folder.
 *
 *   node tools/build-lab-decks.mjs
 *
 * A deck here is a finished lab deck (its own layers, pictures and motion), not a
 * SlideForge lesson, so it is not built through SF.LESSONS: js/lab-engine.js
 * files a card for it and opens the deck as written. Add a deck by adding a row. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DECKS = [
  // Mark Martin MBE: "From a school street to the world stage" (The Air Pollution Project).
  { key: 'air-pollution-story', file: 'assets/air-pollution/Air-Pollution-Story.lesson.json' },
  // Nodes (the Nodes folder): large decks, so only their address is written in; each is fetched from its file when opened.
  { key: 'nodes-critical-text-3', file: 'lessons/nodes/critical-text-3.lesson.json', inline: false },
  { key: 'nodes-describe-three-systems', file: 'lessons/nodes/describe-three-systems.lesson.json', inline: false },
  { key: 'nodes-talk', file: 'lessons/nodes/Nodes-Talk.lesson.json', inline: false },
  { key: 'nodes-cpu-lesson', file: 'lessons/nodes/cpu-lesson.lesson.json', inline: false },
];

const entries = {};
for (const d of DECKS) {
  const deck = JSON.parse(fs.readFileSync(path.join(ROOT, d.file), 'utf8'));
  if (!deck.id || !Array.isArray(deck.slides) || !deck.slides.length) throw new Error(d.file + ': not a lab deck');
  entries[d.key] = { file: d.file, id: deck.id, title: deck.title || d.key, libraryGroup: deck.libraryGroup || '', ...(d.inline === false ? {} : { deck }) };
}
const out = `/* Generated by tools/build-lab-decks.mjs: do not edit by hand, rebuild instead.
   The Lesson studio decks SlideForge ships. A ?lesson=<key> link opens one as it
   was built, and every browser's Library has a card for each under its folder
   (js/lab-engine.js seedShipped), unless the card was deleted there. */
(function (global) {
  'use strict';
  /** @type {any} */
  var SF = global.SF = global.SF || {};
  SF.LAB_DECKS = Object.assign(SF.LAB_DECKS || {}, ${JSON.stringify(entries)});
})(window);
`;
fs.writeFileSync(path.join(ROOT, 'js', 'lab-decks.js'), out);
console.log('js/lab-decks.js: ' + Object.keys(entries).join(', ') + ' · ' + Math.round(out.length / 1024) + ' KB');
